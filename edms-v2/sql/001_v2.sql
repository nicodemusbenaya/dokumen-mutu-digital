CREATE TABLE IF NOT EXISTS v2_documents (
 id CHAR(36) PRIMARY KEY, code VARCHAR(160) NOT NULL UNIQUE, title VARCHAR(500) NOT NULL,
 department VARCHAR(80) NOT NULL, kind VARCHAR(80) NOT NULL, category VARCHAR(500) NOT NULL DEFAULT '',
 owner_id INT UNSIGNED NOT NULL, active_version INT NOT NULL DEFAULT 1, status VARCHAR(20) NOT NULL DEFAULT 'Aktif',
 test_tag VARCHAR(100) NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX idx_v2_docs_updated(updated_at), FOREIGN KEY(owner_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_versions (
 id CHAR(36) PRIMARY KEY, document_id CHAR(36) NOT NULL, number INT NOT NULL, revision VARCHAR(40) NOT NULL,
 title VARCHAR(500) NOT NULL, summary TEXT NOT NULL, actor_id INT UNSIGNED NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), UNIQUE KEY uq_v2_version(document_id,number),
 FOREIGN KEY(document_id) REFERENCES v2_documents(id), FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_files (
 id CHAR(36) PRIMARY KEY, version_id CHAR(36) NOT NULL, name VARCHAR(255) NOT NULL, original_path VARCHAR(1200) NOT NULL,
 extension VARCHAR(10) NOT NULL, origin VARCHAR(20) NOT NULL DEFAULT 'original', source_id CHAR(36) NULL,
 disk_path VARCHAR(500) NOT NULL, sha256 CHAR(64) NOT NULL, size BIGINT NOT NULL, note TEXT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(version_id) REFERENCES v2_versions(id),
 UNIQUE KEY uq_v2_derived(source_id,extension), INDEX idx_v2_hash(sha256)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, actor_id INT UNSIGNED NULL, actor_name VARCHAR(120) NOT NULL,
 action VARCHAR(80) NOT NULL, document_id CHAR(36) NULL, context_json LONGTEXT NOT NULL,
 ip VARCHAR(80) NULL, device VARCHAR(500) NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX idx_v2_audit_doc(document_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_uploads (
 id CHAR(36) PRIMARY KEY, actor_id INT UNSIGNED NOT NULL, name VARCHAR(255) NOT NULL, size BIGINT NOT NULL,
 parts INT NOT NULL, metadata LONGTEXT NOT NULL, state VARCHAR(30) NOT NULL DEFAULT 'uploading',
 expires_at DATETIME NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(actor_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_parts (
 upload_id CHAR(36) NOT NULL, number INT NOT NULL, size INT NOT NULL, sha256 CHAR(64) NOT NULL,
 PRIMARY KEY(upload_id,number), FOREIGN KEY(upload_id) REFERENCES v2_uploads(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_jobs (
 id CHAR(36) PRIMARY KEY, actor_id INT UNSIGNED NOT NULL, kind VARCHAR(30) NOT NULL, upload_id CHAR(36) NULL,
 source_id CHAR(36) NULL, target VARCHAR(10) NULL, state VARCHAR(30) NOT NULL DEFAULT 'queued',
 attempts INT NOT NULL DEFAULT 0, lease_until DATETIME NULL, worker_id CHAR(36) NULL, progress INT NOT NULL DEFAULT 0,
 error TEXT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(actor_id) REFERENCES users(id), INDEX idx_v2_queue(state,lease_until)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_import_items (
 id CHAR(36) PRIMARY KEY, job_id CHAR(36) NOT NULL, original_path VARCHAR(1200) NOT NULL,
 state VARCHAR(30) NOT NULL, stage VARCHAR(40) NOT NULL, error TEXT NULL, document_id CHAR(36) NULL, file_id CHAR(36) NULL, payload_json LONGTEXT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY(job_id) REFERENCES v2_jobs(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_rate_limits (
 bucket CHAR(64) PRIMARY KEY, hits INT NOT NULL, expires_at DATETIME NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS v2_migrations (
 version VARCHAR(80) PRIMARY KEY, applied_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, detail TEXT NULL
) ENGINE=InnoDB;
