import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const before=JSON.parse(await fs.readFile('/evidence/before.json','utf8'));
const next=structuredClone(before),app=next.services['edms-app'];
assert.equal(app.container_name,'edms-ups-app');
assert.equal(app.image,'edms-ups:2.1.3');
assert(!app.build,'NAS must not build');
assert.equal(app.working_dir,'/opt/edms');
assert.deepEqual(app.command,['node','scripts/start.mjs']);
assert(app.volumes.some(v=>v.target==='/app/storage'&&v.type==='bind'));
app.image='edms-ups:2.1.4';
const compare=structuredClone(next);compare.services['edms-app'].image=before.services['edms-app'].image;
assert.deepEqual(compare,before,'Only application image may change');
await fs.writeFile('/evidence/next.json',JSON.stringify(next,null,2),{flag:'wx',mode:0o600});
console.log('UI_IMAGE_ONLY_CONFIG_PASS');
